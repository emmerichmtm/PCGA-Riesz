"""Rebuild the paper's occupancy plot, table and statistics from measured runs.

Run after scale.py, paired.py and validation.py, or directly against the
distributed compact records. Representative lists are regenerated by the
experiment; the compact records store their SHA-256 (ordered little-endian u64).
"""
import hashlib, json
from collections import Counter, defaultdict
from fractions import Fraction as F
from pathlib import Path
from statistics import median
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / 'measurements'
OUT = ROOT / 'results'
OUT.mkdir(exist_ok=True)
CAPS = (0,1,2,3,5,10)
METHODS = ('pair_count','packing','incumbent','exchange','hybrid')

def load_records(filename, compact_name, paired=False):
    compact = OUT / compact_name
    if not filename.exists():
        with compact.open('r', encoding='utf8') as src:
            return [json.loads(line) for line in src]
    rows = []
    with filename.open(encoding='utf8') as src, compact.open('w', encoding='utf8') as dst:
        for line in src:
            row = json.loads(line)
            grids = row['methods'] if paired else (row['grid'],)
            for g in grids:
                indices = g.pop('representatives')
                assert len(indices)==g['M']
                g['representatives_sha256'] = hashlib.sha256(np.asarray(indices,dtype='<u8').tobytes()).hexdigest()
            if not paired:
                row.pop('ablation', None)  # all requested caps are prefixes of the retained trace
            dst.write(json.dumps(row, separators=(',',':'))+'\n')
            rows.append(row)
    return rows

def scale_summary(rows):
    assert len(rows)==len({r['id'] for r in rows})==156
    assert {r['config']['epsilon'] for r in rows}=={'1/2','1'}
    good=[r for r in rows if r['base']['status']=='complete']
    repeat=defaultdict(list)
    pass_counts=Counter()
    heur=Counter()
    tiny=[]
    def group(**spec):
        return [r for r in rows if all(r['config'].get(k)==v for k,v in spec.items()) and 'translation' not in r['config']]
    def counts(rs):
        assert len(rs)==3
        return sorted(r['grid']['M'] for r in rs)
    for r in good:
        trace=r['refine']['trace']; v=F(r['base']['energy_exact'])
        e=[F(z['energy_exact']) for z in trace]
        assert v==e[0] and all(a>=b for a,b in zip(e,e[1:]))
        pass_counts[next(i for i,a in enumerate(e) if a==e[-1])]+=1
        other=F(r['global_two_sweep_baseline']['trace'][-1]['energy_exact'])
        heur['lower' if e[-1]<other else 'higher' if e[-1]>other else 'equal']+=1
        if 'tiny_optimum' in r['groups']:
            opt=F(r['original_optimum']['energy_exact'])
            assert opt<=e[-1]<=v<=(1+F(r['config']['epsilon']))*opt
            tiny.append(e[-1]==opt)
        for t in CAPS:
            z=trace[min(t,len(trace)-1)]
            gain=float(100*(1-F(z['energy_exact'])/v))
            p=r['grid']['prep_seconds']; s=r['base']['search_seconds']; x=z['seconds']
            repeat[t].append([float(F(z['energy_exact'])),gain,1000*p,1000*s,1000*x,1000*(p+s+x)])
    cfg=dict(k=5,c=10,kind='clusters')
    million=group(n=10**6,k=5,c=10,kind='clusters',rho='1/4096',epsilon='1/2')
    return dict(n=len(rows),status=dict(Counter(r['base']['status'] for r in rows)),
        accuracy_frequency=dict(Counter(r['config']['epsilon'] for r in rows)),
        million_tight=counts(million),
        million_uniform=counts(group(n=10**6,k=5,c=10,kind='uniform',rho='1/4096',epsilon='1/2')),
        million_seconds=[median(r['grid']['prep_seconds'] for r in million),median(r['base']['search_seconds'] for r in million)],
        accuracy={eps:counts(group(n=10000,rho='1/1024',epsilon=eps,**cfg)) for eps in ('1/2','1')},
        widths={rho:counts(group(n=10**5,rho=rho,epsilon='1/2',**cfg)) for rho in ('1/4096','1/1024','1/256')},
        communities={str(c):counts(group(n=10**5,k=5,c=c,kind='clusters',rho='1/4096',epsilon='1/2')) for c in (5,10,25,50)},
        cap_columns=['energy','gain_percent','prep_ms','search_ms','extra_ms','total_ms'],
        caps={str(t):list(map(median,zip(*repeat[t]))) for t in CAPS},
        earliest_final_sweep=dict(pass_counts),maximum_gain=max(a[1] for a in repeat[10]),
        versus_heuristic=dict(heur),tiny_optima=[sum(tiny),len(tiny)])

def paired_summary(rows):
    assert len(rows)==len({r['id'] for r in rows})==114
    assert {r['config']['epsilon'] for r in rows}=={'1/2'}
    grouped=defaultdict(list); order=Counter(); statuses={m:Counter() for m in METHODS}
    for r in rows:
        c=r['config']; d={v['method']:v for v in r['methods']}
        assert set(d)==set(METHODS)
        i,x,h=[d[m]['M'] for m in ('incumbent','exchange','hybrid')]
        assert h==min(i,x)
        assert len({v['origin'] for v in d.values()})==1
        order['lower' if x<i else 'equal' if x==i else 'higher']+=1
        for m,v in d.items():
            statuses[m][v['status']]+=1
            if 'optimum_exact' in v:
                assert F(v['optimum_exact'])<=F(v['refined_energy_exact'])<=F(v['energy_exact'])<=F(3,2)*F(v['optimum_exact'])
        grouped[(c['group'],c['family'],c['n'],c['k'],c['rho'],c['offset'])].append(d)
    def vals(key,m):
        a=[d[m]['M'] for d in grouped[key]]; assert len(a)==3
        return sorted(a)
    def medcounts(key):return [vals(key,m)[1] for m in METHODS]
    tab=[]
    for key in grouped:
        _,fam,n,k,rho,o=key
        tab.append(f'{fam} & ${rho}$ & {n} & {k} & ${o}$ & '+' & '.join(map(str,medcounts(key)))+r'\\')
    (OUT/'paired-rows.tex').write_text('\n'.join(tab)+'\n',encoding='utf8')
    # These plot commands are inserted in both papers; the caption and legend
    # remain outside this generated portion.
    lines=[r'\nextgroupplot[title={Lattice centers},title style={font=\small},legend to name=paired-v2-legend]']
    style=['black!60,mark=triangle*','blue!70!black,mark=square*','green!45!black,mark=*','orange!90!black,mark=diamond*']
    for fam in ('lattice','irregular'):
        if fam=='irregular':lines.append(r'\nextgroupplot[title={Irregular centers},title style={font=\small}]')
        for m,sty,tag in zip(METHODS,style,('Pair count','Packing','Incumbent','Exchange')):
            series=[]
            for k in (8,16,32,64,128,256,512):
                lo,mid,hi=vals(('cardinality',fam,100000,k,'1/256','0'),m)
                lines.append(r'\addplot[forget plot,'+sty.split(',')[0]+f',thin] coordinates {{({k},{lo}) ({k},{hi})}};')
                series.append(f'({k},{mid})')
            lines.append(r'\addplot['+sty+',mark size=1.5pt] coordinates {'+' '.join(series)+'};')
            if fam=='lattice':lines.append(r'\addlegendentry{'+tag+'}')
    (OUT/'paired-series.tex').write_text('\n'.join(lines)+'\n',encoding='utf8')
    return dict(cases=len(rows),arrays=len({r['input_sha256'] for r in rows}),status=statuses,
                exchange_vs_incumbent=order,small=medcounts(('geometry','irregular',2000,5,'1/1024','0')),
                k512={fam:medcounts(('cardinality',fam,100000,512,'1/256','0')) for fam in ('lattice','irregular')})

def check_fresh(records):
    assert len(records)==9 and all(x['config']['epsilon']=='1/2' for x in records)
    return [dict(n=r['config']['n'],kind=r['config']['kind'],seed=r['config']['seed'],M=r['M'],
        gain=r['observations'][-1]['gain_percent'],
        optimum_attained=F(r['observations'][-1]['energy_exact'])==F(r['optimum_exact']) if r['optimum_exact'] else None)
        for r in records]

if __name__=='__main__':
    scale=load_records(RAW/'results-v2.jsonl','scale.jsonl')
    paired=load_records(RAW/'paired'/'results-v2.jsonl','paired.jsonl',paired=True)
    val=RAW/'validation.json'
    a=dict(scale=scale_summary(scale),paired=paired_summary(paired),fresh=check_fresh(json.loads(val.read_text())))
    (OUT/'summary.json').write_text(json.dumps(a,indent=2),encoding='utf8')
    print(json.dumps(a,indent=2))
